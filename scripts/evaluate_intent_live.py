"""Explicitly authorized DEV-only candidate experiment through original Gateway/Journal.

This host evaluation harness is NOT a new Web model route or Agent Runtime.
No authorization file is generated by this command. No business Run is launched.
"""

import argparse
import hashlib
import json
import os
import time
from datetime import date
from pathlib import Path
from uuid import NAMESPACE_URL, uuid4, uuid5

from evaluate_intent import read_cases
from p7_isolated_pg import environment, inspect

from datapilot.config import Settings
from datapilot.contracts import AgentFailure
from datapilot.evaluation import IntentGold, IntentObservation, intent_summary, signature
from datapilot.ingestion.common import digest
from datapilot.orchestration.contracts import BudgetLimits
from datapilot.orchestration.model import Gateway, live_transport
from datapilot.persistence.backend import Backend, DurableArtifacts, DurableLedger, execute
from datapilot.persistence.journal import Journal
from datapilot.persistence.session import PersistentCancellation, run_async
from datapilot.web.chat_contracts import ChatSelection
from datapilot.web.semantic_intent import INTENT_VERSION, SYSTEM, resolve_candidate

ROOT = Path(__file__).resolve().parents[1]


async def main(args):
    auth = json.loads(args.authorization.read_text(encoding="utf-8"))
    if auth.get("allowed") is not True or auth.get("phase") != "p7-gate1-dev":
        raise ValueError("Needs an explicit human-approved P7 DEV authorization")
    if args.strategy not in auth.get("strategies", []):
        raise ValueError("Strategy was not authorized")
    for name, sha in auth["source_hashes"].items():
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != sha:
            raise ValueError("Approved candidate source changed; rerun engineering checks first")
    ids = auth["case_ids"]
    if not 1 <= len(ids) <= 12 or len(ids) != len(set(ids)):
        raise ValueError("Use 1–12 individually authorized development cases")
    inspect()
    os.environ.update(environment())
    cases = {c["case_id"]: c for c in read_cases("dev")}
    if not set(ids) <= set(cases):
        raise ValueError("Only development IDs are allowed; never reads Holdout")
    selected = [cases[k] for k in ids]
    settings = Settings(
        llm_mode="live",
        max_model_calls=auth["calls_per_strategy"],
        max_total_tokens=auth["tokens_per_strategy"],
        max_output_tokens=768,
    )
    if (
        settings.model_provider != "deepseek"
        or settings.model != "deepseek-flash"
        or settings.base_url.rstrip("/")
        not in {"https://api.deepseek.com", "https://api.deepseek.com/v1"}
    ):
        raise ValueError("Model destination/profile differs from the explicit authorization")
    if not 1 <= settings.max_model_calls <= 12 or settings.max_total_tokens > 75000:
        raise ValueError("P7 pilot maximum is 12 calls/75,000 tokens per strategy")
    manifest = {
        "purpose": "p7-gate1-dev",
        "authorization_sha256": digest(auth),
        "strategy": args.strategy,
        "cases_sha256": digest(selected),
        "intent_version": INTENT_VERSION,
        "prompt_sha256": digest(SYSTEM),
        "source_sha256": digest(
            (ROOT / "src/datapilot/web/semantic_intent.py").read_text(encoding="utf-8")
        ),
        "model_profile": {
            "provider": settings.model_provider,
            "model": settings.model,
            "endpoint": settings.base_url,
            "thinking": "disabled",
            "max_output_tokens": 768,
            "calls": settings.max_model_calls,
            "tokens": settings.max_total_tokens,
        },
    }
    run_id = str(uuid5(NAMESPACE_URL, "p7-intent-dev:" + auth["authorization_id"] + args.strategy))
    backend = Backend(settings.runtime_database_url.get_secret_value(), run_id, "p7-intent-dev")
    limits = BudgetLimits(calls=settings.max_model_calls, tokens=settings.max_total_tokens)
    output = ROOT / "artifacts/p7" / ("intent-live-" + args.strategy + "-" + str(uuid4()) + ".json")
    try:
        with backend.lease():
            with backend.engine.connect() as conn:
                exists = execute(
                    conn, "SELECT 1 FROM execution.runs WHERE run_id=:r", r=run_id
                ).first()
            if exists and not args.resume:
                raise ValueError("Campaign exists; explicit --resume required, never start again")
            backend.register(manifest, limits)
            ledger = DurableLedger(backend, limits)
            journal = Journal(backend, ledger, DurableArtifacts(backend))
            if exists:
                journal.recover()  # Unknown outcome blocks, committed calls replay unchanged.
            gateway = Gateway(
                live_transport(settings), settings, ledger, PersistentCancellation(backend)
            )
            gateway.durability = journal
            observations = []
            for case in selected:
                before, started = ledger.snapshot(), time.perf_counter()
                try:
                    draft = await resolve_candidate(
                        case["question"],
                        ChatSelection.model_validate_json(json.dumps(case["selection"])),
                        case["datasets"],
                        today=date.fromisoformat(case["today"]),
                        previous=case["previous"],
                        gateway=gateway,
                        strategy=args.strategy,
                    )
                    actual, code = signature(draft), None
                except AgentFailure as exc:
                    actual, code = None, exc.error.code
                after = ledger.snapshot()
                observations.append(
                    IntentObservation(
                        case_id=case["case_id"],
                        strategy=args.strategy,
                        transport="live",
                        expected=IntentGold.model_validate_json(json.dumps(case["expected"])),
                        actual=actual,
                        error_code=code,
                        elapsed_ms=(time.perf_counter() - started) * 1000,
                        model_calls=after.calls - before.calls,
                        reported_tokens=after.reported_tokens - before.reported_tokens
                        if after.usage_complete
                        else None,
                    )
                )
                result = {
                    "run_id": run_id,
                    "manifest_sha256": digest(manifest),
                    "observations": [o.model_dump(mode="json") for o in observations],
                    "summary": intent_summary(observations),
                    "ledger": after.model_dump(),
                    "complete": len(observations) == len(selected),
                    "billed_cost": None,
                    "estimated_cost": None,
                    "cost_status": (
                        "Compute only from inspected original provider receipts "
                        "and verified dated pricing"
                    ),
                    "agent_execution": "not_run",
                }
                output.write_text(
                    json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8"
                )
                if code:
                    # Do not mask or automatically retry an issued/unknown provider request.
                    raise AgentFailure(code, "Pilot stopped; preserve original Journal and budget")
            print(json.dumps(result["summary"], ensure_ascii=False))
    finally:
        backend.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--authorization", type=Path, required=True)
    parser.add_argument("--strategy", choices=["llm_only", "hybrid"], required=True)
    parser.add_argument("--resume", action="store_true")
    run_async(main(parser.parse_args()))
